import type {
  Confidence,
  Forecast,
  ForecastPoint,
  TermInsight,
  TrendDirection,
} from "../shared/types.ts";

const MAX_INTEREST = 100;
const GRID_ALPHA = [0.15, 0.25, 0.35, 0.5, 0.65, 0.8, 0.9];
const GRID_BETA = [0.02, 0.05, 0.1, 0.2, 0.35, 0.5];
const GRID_PHI = [0.8, 0.85, 0.9, 0.95, 0.98, 1];
const Z_80 = 1.2816;

interface Model {
  alpha: number;
  beta: number;
  phi: number;
  level: number;
  trend: number;
  errors: number[];
}

function clampInterest(value: number) {
  return Math.min(MAX_INTEREST, Math.max(0, value));
}

function directionOf(changePct: number): TrendDirection {
  if (changePct > 2) return "up";
  if (changePct < -2) return "down";
  return "flat";
}

/**
 * Run Holt's linear trend with a damped slope across a series.
 *
 * Alpha is the level smoothing factor, beta the trend factor, and phi the
 * damping in (0, 1]. A damped slope keeps a short hot streak from projecting a
 * straight line to 100 forever, which raw linear regression does on query data.
 * Returns one-step-ahead errors so the caller can score the fit.
 */
function runModel(values: number[], alpha: number, beta: number, phi: number): Model {
  let level = values[0] ?? 0;
  let trend = (values[1] ?? level) - level;
  const errors: number[] = [];

  for (let index = 1; index < values.length; index += 1) {
    const actual = values[index] ?? level;
    const predicted = level + phi * trend;
    errors.push(actual - predicted);

    const previousLevel = level;
    level = alpha * actual + (1 - alpha) * (level + phi * trend);
    trend = beta * (level - previousLevel) + (1 - beta) * phi * trend;
  }

  return { alpha, beta, phi, level, trend, errors };
}

/** Grid-search smoothing parameters by one-step SSE; deterministic by construction. */
function fitBest(values: number[]): Model {
  let best: Model | null = null;
  let bestSse = Number.POSITIVE_INFINITY;

  for (const alpha of GRID_ALPHA) {
    for (const beta of GRID_BETA) {
      for (const phi of GRID_PHI) {
        const model = runModel(values, alpha, beta, phi);
        const sse = model.errors.reduce((total, error) => total + error * error, 0);
        if (sse < bestSse) {
          bestSse = sse;
          best = model;
        }
      }
    }
  }

  return (
    best ?? { alpha: 0.5, beta: 0.1, phi: 0.9, level: values.at(-1) ?? 0, trend: 0, errors: [] }
  );
}

/** Project `horizon` steps and widen the interval with the square root of distance. */
function project(model: Model, horizon: number, rmse: number): ForecastPoint[] {
  const points: ForecastPoint[] = [];
  let damping = 0;

  for (let step = 1; step <= horizon; step += 1) {
    damping += model.phi ** step;
    const value = clampInterest(model.level + model.trend * damping);
    const spread = Math.max(2.5, Z_80 * rmse * Math.sqrt(1 + 0.12 * step));
    points.push({
      time: 0,
      date: "",
      value: Math.round(value * 10) / 10,
      lower: Math.round(clampInterest(value - spread) * 10) / 10,
      upper: Math.round(clampInterest(value + spread) * 10) / 10,
    });
  }

  return points;
}

function mapeFor(actual: number[], predicted: number[]) {
  const pairs = actual.map((value, index) => [value, predicted[index]] as const);
  const errors = pairs
    .filter(([value]) => Number.isFinite(value))
    .map(([value, guess]) => Math.abs(value - (guess ?? value)) / Math.max(5, value));
  return (errors.reduce((total, error) => total + error, 0) / errors.length) * 100;
}

/** Hold out the last four observations so accuracy is measured, not asserted. */
function backtest(values: number[]): number | null {
  if (values.length < 12) return null;
  const holdout = 4;
  const train = values.slice(0, -holdout);
  const actual = values.slice(-holdout);
  const model = fitBest(train);
  const rmse = Math.sqrt(
    model.errors.reduce((total, error) => total + error * error, 0) /
      Math.max(1, model.errors.length),
  );
  const predicted = project(model, holdout, rmse).map((point) => point.value);
  const mape = mapeFor(actual, predicted);
  return Number.isFinite(mape) ? Math.round(mape * 10) / 10 : null;
}

function confidenceOf(mape: number | null, sampleSize: number): Confidence {
  if (mape === null) return sampleSize >= 20 ? "medium" : "low";
  if (mape <= 10) return "high";
  if (mape <= 20) return "medium";
  return "low";
}

/**
 * Build the forecast for one term.
 *
 * `times` and `values` are parallel arrays sorted oldest-first. The returned
 * forecast points carry dates generated by stepping the observed cadence, so a
 * weekly series stays weekly and a daily series stays daily even across DST.
 * Values are clamped to Google's 0–100 index, not extrapolated past it.
 */
export function buildForecast(values: number[], times: number[], horizon: number): Forecast {
  const cleanValues: number[] = [];
  const cleanTimes: number[] = [];

  values.forEach((value, index) => {
    const time = times[index];
    if (Number.isFinite(value) && Number.isFinite(time)) {
      cleanValues.push(value);
      cleanTimes.push(time);
    }
  });

  const lastValue = cleanValues.at(-1) ?? 0;
  const lastTime = cleanTimes.at(-1) ?? Math.floor(Date.now() / 1000);
  const cadence =
    cleanTimes.length > 1
      ? Math.max(86000, Math.round((lastTime - (cleanTimes.at(-2) ?? lastTime)) / 1))
      : 7 * 86400;

  if (cleanValues.length < 4) {
    const points = Array.from({ length: horizon }, (_, index) => ({
      time: lastTime + cadence * (index + 1),
      date: new Date((lastTime + cadence * (index + 1)) * 1000).toISOString(),
      value: lastValue,
      lower: clampInterest(lastValue - 10),
      upper: clampInterest(lastValue + 10),
    }));
    return {
      points,
      next: lastValue,
      changePct: 0,
      direction: "flat",
      confidence: "low",
      mape: null,
      model: "holt-damped-trend",
      horizon,
    };
  }

  const model = fitBest(cleanValues);
  const sse = model.errors.reduce((total, error) => total + error * error, 0);
  const rmse = Math.sqrt(sse / Math.max(1, model.errors.length));
  const basePoints = project(model, horizon, rmse);
  const points = basePoints.map((point, index) => {
    const time = lastTime + cadence * (index + 1);
    return {
      ...point,
      time,
      date: new Date(time * 1000).toISOString(),
    };
  });

  const endpoint = points.at(-1)?.value ?? lastValue;
  const changePct = lastValue > 0 ? ((endpoint - lastValue) / lastValue) * 100 : 0;
  const mape = backtest(cleanValues);

  return {
    points,
    next: points[0]?.value ?? lastValue,
    changePct: Math.round(changePct * 10) / 10,
    direction: directionOf(changePct),
    confidence: confidenceOf(mape, cleanValues.length),
    mape,
    model: "holt-damped-trend",
    horizon,
  };
}

/**
 * Summarize one term's history for the dashboard and watchlist.
 * Related queries and regions are attached by the data layer, which owns those
 * secondary widgets; this function only needs the primary timeline.
 */
export function buildInsight(
  term: string,
  values: number[],
  times: number[],
  horizon: number,
): TermInsight {
  const pairs = values
    .map((value, index) => ({ value, time: times[index] }))
    .filter(
      (pair): pair is { value: number; time: number } =>
        Number.isFinite(pair.value) && Number.isFinite(pair.time),
    );

  const cleanValues = pairs.map((pair) => pair.value);
  const cleanTimes = pairs.map((pair) => pair.time);
  const latest = cleanValues.at(-1) ?? 0;
  const previous = cleanValues.at(-2) ?? latest;
  const changePct = previous > 0 ? ((latest - previous) / previous) * 100 : 0;
  const recent = cleanValues.slice(-4);
  const prior = cleanValues.slice(-8, -4);
  const priorAverage = prior.length
    ? prior.reduce((total, value) => total + value, 0) / prior.length
    : latest;
  const momentum = priorAverage > 0 ? ((recent.at(-1) ?? latest) - priorAverage) / priorAverage : 0;
  let peakIndex = 0;

  cleanValues.forEach((value, index) => {
    if (value > (cleanValues[peakIndex] ?? Number.NEGATIVE_INFINITY)) peakIndex = index;
  });

  return {
    term,
    latest: Math.round(latest * 10) / 10,
    previous: Math.round(previous * 10) / 10,
    peak: cleanValues[peakIndex] ?? 0,
    peakTime: cleanTimes[peakIndex] ?? 0,
    latestTime: cleanTimes.at(-1) ?? 0,
    sampleSize: cleanValues.length,
    history: pairs.map((pair) => ({
      time: pair.time,
      date: new Date(pair.time * 1000).toISOString(),
      value: Math.round(pair.value * 10) / 10,
    })),
    changePct: Math.round(changePct * 10) / 10,
    direction: directionOf(changePct),
    momentum: Math.round(momentum * 1000) / 10,
    forecast: buildForecast(cleanValues, cleanTimes, horizon),
    sparkline: cleanValues.slice(-20),
    related: [],
    regions: [],
  };
}
